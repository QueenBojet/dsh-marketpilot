import { randomUUID } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import { createServices } from '../src/services/index.ts'
import { setup, requirement, evidence, alternative, tender, confirmedRequirement } from './helpers.ts'

describe.each(['sqlite', 'json'] as const)('%s project services', medium => {
  it('creates, reads, updates and deletes projects without exposing mutable state', async () => {
    const { services: s, project } = await setup(medium)
    expect(s.projects.list()).toHaveLength(1)
    const copy = s.projects.get(project.id)!
    copy.name = 'mutation'
    expect(s.projects.get(project.id)?.name).toBe(project.name)
    await s.projects.update(project.id, { name: 'changed' })
    expect(s.projects.get(project.id)?.name).toBe('changed')
    expect(await s.projects.delete(project.id)).toBe(true)
    expect(s.projects.get(project.id)).toBeNull()
  })
  it('supports source, requirement, evidence, alternative, tender and artifact CRUD', async () => {
    const { services: s, project: p } = await setup(medium)
    const doc = await s.documents.add(p.id, { name: '需求.md', kind: 'customer_requirement', textContent: '持续监测' })
    await s.documents.update(p.id, doc.id, { textContent: '连续监测' })
    const [r] = await s.requirements.addMany(p.id, [{ ...requirement, sourceDocumentId: doc.id }])
    await s.requirements.update(p.id, r!.id, { priority: 'should' })
    expect(s.requirements.get(p.id, r!.id).priority).toBe('should')
    const e = await s.evidence.add(p.id, evidence)
    await s.evidence.update(p.id, e.id, { title: '新标题' })
    const [a] = await s.alternatives.addMany(p.id, [alternative])
    await s.alternatives.update(p.id, a!.id, { name: '候选 B' })
    const t = await s.tender.add(p.id, tender)
    await s.tender.update(p.id, t.id, { status: 'non_compliant' })
    const artifact = await s.artifacts.save(p.id, { type: 'other', name: 'Notes.md', content: '# Notes', format: 'markdown' })
    await s.artifacts.update(p.id, artifact.id, { content: '# Updated' })
    expect(s.artifacts.get(p.id, artifact.id).content).toBe('# Updated')
    await s.artifacts.delete(p.id, artifact.id)
    await s.tender.delete(p.id, t.id)
    await s.alternatives.delete(p.id, a!.id)
    await s.evidence.delete(p.id, e.id)
    await s.requirements.delete(p.id, r!.id)
    await s.documents.delete(p.id, doc.id)
    expect(s.documents.list(p.id)).toEqual([])
  })
  it('links evidence only to records in the same project and blocks dangling deletions', async () => {
    const { services: s, project: p } = await setup(medium)
    const [r] = await s.requirements.addMany(p.id, [requirement])
    const e = await s.evidence.add(p.id, evidence)
    const [a] = await s.alternatives.addMany(p.id, [alternative])
    const c = await s.competitors.upsert(p.id, { company: '匿名厂商', product: 'M1', performance: { sensitivity: null }, interfaces: [], certifications: [], cases: [], strengths: [], limitations: [], evidenceIds: [e.id] })
    await s.evidence.link(p.id, e.id, { relatedRequirementIds: [r!.id], relatedCompetitorIds: [c.id], relatedAlternativeIds: [a!.id] })
    expect(s.evidence.get(p.id, e.id).relatedRequirementIds).toEqual([r!.id])
    await expect(s.requirements.delete(p.id, r!.id)).rejects.toThrow(/reference/)
    const other = await s.projects.create({ name: 'another' })
    const [foreign] = await s.requirements.addMany(other.id, [requirement])
    await expect(s.evidence.link(p.id, e.id, { relatedRequirementIds: [foreign!.id] })).rejects.toThrow(/reference/)
    expect(s.evidence.get(p.id, e.id).relatedRequirementIds).toEqual([r!.id])
  })
  it('protects UNKNOWN from automatic FACT updates and supports audited human resolution', async () => {
    const { services: s, project: p } = await setup(medium)
    const u = await s.evidence.add(p.id, { ...evidence, kind: 'UNKNOWN', sourceType: 'model', statement: '最小检漏率未冻结' })
    await expect(s.evidence.update(p.id, u.id, { kind: 'FACT' })).rejects.toMatchObject({ code: 'UNKNOWN_PROTECTED' })
    await expect(s.evidence.verify(p.id, u.id, { method: 'new_evidence', targetKind: 'FACT', statement: '确认值' })).rejects.toMatchObject({ code: 'UNKNOWN_PROTECTED' })
    expect(s.evidence.get(p.id, u.id).kind).toBe('UNKNOWN')
    const verified = await s.evidence.verify(p.id, u.id, { method: 'human', targetKind: 'FACT', statement: '人工确认的测试值' })
    expect(verified).toMatchObject({ kind: 'FACT', status: 'verified', verification: { fromKind: 'UNKNOWN', method: 'human' } })
    await expect(s.evidence.update(p.id, u.id, { statement: 'overwrite' })).rejects.toMatchObject({ code: 'EVIDENCE_IMMUTABLE' })
  })
  it('requires matching new verified evidence for automated resolution', async () => {
    const { services: s, project: p, advance } = await setup(medium)
    const u = await s.evidence.add(p.id, { ...evidence, kind: 'UNKNOWN' })
    advance(100)
    const source = await s.evidence.add(p.id, evidence)
    await s.evidence.verify(p.id, source.id, { method: 'human', targetKind: 'SOURCE', statement: evidence.statement })
    await expect(s.evidence.verify(p.id, u.id, { method: 'new_evidence', targetKind: 'FACT', statement: '另一声明', supportingEvidenceIds: [source.id] })).rejects.toMatchObject({ code: 'UNSUPPORTED_RESOLUTION' })
    const result = await s.evidence.verify(p.id, u.id, { method: 'new_evidence', targetKind: 'FACT', statement: evidence.statement, supportingEvidenceIds: [source.id] })
    expect(result.verification?.supportingEvidenceIds).toEqual([source.id])
  })
  it('supports human keep-unknown and reject resolutions through the same gate', async () => {
    const { services: s, project: p } = await setup(medium)
    const u = await s.evidence.add(p.id, { ...evidence, kind: 'UNKNOWN', sourceType: 'model', statement: '最小检漏率未冻结' })
    // Automated keep-unknown/reject is forbidden — both need the human gate.
    await expect(s.evidence.verify(p.id, u.id, { method: 'new_evidence', targetKind: 'UNKNOWN', statement: u.statement })).rejects.toMatchObject({ code: 'UNKNOWN_PROTECTED' })
    await expect(s.evidence.verify(p.id, u.id, { method: 'new_evidence', targetKind: 'REJECT', statement: u.statement })).rejects.toMatchObject({ code: 'UNKNOWN_PROTECTED' })
    // Human keep-unknown: kind stays UNKNOWN, status becomes verified, fromKind recorded.
    const kept = await s.evidence.verify(p.id, u.id, { method: 'human', targetKind: 'UNKNOWN', statement: u.statement })
    expect(kept).toMatchObject({ kind: 'UNKNOWN', status: 'verified', verification: { fromKind: 'UNKNOWN', method: 'human' } })
    // Human reject: statement and kind keep their original values, status rejected.
    const r = await s.evidence.add(p.id, { ...evidence, kind: 'INFERENCE', statement: '红外对全部油膜高灵敏' })
    const rejected = await s.evidence.verify(p.id, r.id, { method: 'human', targetKind: 'REJECT', statement: r.statement })
    expect(rejected).toMatchObject({ kind: 'INFERENCE', status: 'rejected', verification: { fromKind: 'INFERENCE', method: 'human' } })
    expect(rejected.statement).toBe('红外对全部油膜高灵敏')
    // A settled record (either way) can no longer be re-verified.
    await expect(s.evidence.verify(p.id, u.id, { method: 'human', targetKind: 'FACT', statement: u.statement })).rejects.toMatchObject({ code: 'EVIDENCE_IMMUTABLE' })
  })
  it('does not mark parameter clause compliant without evidence', async () => {
    const { services: s, project: p } = await setup(medium)
    const result = await s.tender.add(p.id, tender)
    expect(result.status).toBe('unknown')
    expect(result.action).toBeTruthy()
    expect((await s.tender.update(p.id, result.id, { status: 'compliant' })).status).toBe('unknown')
  })
  it.each(['certification', 'track_record', 'model_performance'])('requires evidence for %s', async claim => {
    const { services: s, project: p } = await setup(medium)
    const result = await s.tender.add(p.id, { ...tender, claimKinds: [claim] })
    expect(result.status).toBe('unknown')
  })
  it('rejects invented evidence IDs and does not use unverified evidence as compliance support', async () => {
    const { services: s, project: p } = await setup(medium)
    await expect(s.tender.add(p.id, { ...tender, evidenceIds: [randomUUID()] })).rejects.toThrow(/reference/)
    const e = await s.evidence.add(p.id, evidence)
    expect((await s.tender.add(p.id, { ...tender, evidenceIds: [e.id] })).status).toBe('unknown')
    await s.evidence.verify(p.id, e.id, { method: 'human', targetKind: 'SOURCE', statement: evidence.statement })
    expect((await s.tender.add(p.id, { ...tender, evidenceIds: [e.id] })).status).toBe('compliant')
  })
  it('uses the human gate to atomically select a decision and keeps history', async () => {
    const { services: s, repository, project: p } = await setup(medium)
    const r = await confirmedRequirement(s, p.id)
    const [a, b] = await s.alternatives.addMany(p.id, [alternative, { ...alternative, name: 'B' }])
    const request = { alternativeId: a!.id, decision: '采用 A', rationale: '人工比选', requirementIds: [r], evidenceIds: [] }
    const withoutHumanGate = createServices(repository)
    await expect(withoutHumanGate.decisions.confirm(p.id, request)).rejects.toMatchObject({ code: 'HUMAN_GATE_UNAVAILABLE' })
    expect(s.decisions.list(p.id)).toHaveLength(0)
    const first = await s.decisions.confirm(p.id, request)
    expect(s.projects.getContext(p.id).selectedDecision?.id).toBe(first.id)
    await expect(s.alternatives.update(p.id, a!.id, { summary: 'change' })).rejects.toMatchObject({ code: 'DECISION_REFERENCED' })
    await s.decisions.confirm(p.id, { ...request, alternativeId: b!.id, decision: '采用 B' })
    expect(s.decisions.list(p.id)).toHaveLength(2)
    expect(s.alternatives.list(p.id).filter(a => a.status === 'selected').map(a => a.id)).toEqual([b!.id])
    expect(s.evidence.list(p.id).filter(e => e.kind === 'DECISION')).toHaveLength(2)
  })
  it('does not partially write a decision with invalid references', async () => {
    const { services: s, project: p } = await setup(medium)
    const r = await confirmedRequirement(s, p.id)
    const [a] = await s.alternatives.addMany(p.id, [alternative])
    await expect(s.decisions.confirm(p.id, { alternativeId: a!.id, decision: 'A', rationale: 'review', requirementIds: [r], evidenceIds: [randomUUID()] })).rejects.toThrow()
    expect(s.decisions.list(p.id)).toHaveLength(0)
    expect(s.alternatives.get(p.id, a!.id).status).toBe('candidate')
    expect(s.projects.get(p.id)?.activeDecisionId).toBeUndefined()
  })
})
