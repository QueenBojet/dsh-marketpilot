import { describe, expect, it } from 'vitest'
import { setup, requirement, alternative, confirmedRequirement, approved } from './helpers.ts'
import { createServices } from '../src/services/index.ts'

describe('workflow runs', () => {
  it('returns prerequisite_error before confirmed requirements and waits for a human Decision', async () => {
    const { services: s, project: p } = await setup()
    expect((await s.workflows.start(p.id, { type: 'solution_generation' })).status).toBe('failed')
    const r = await confirmedRequirement(s, p.id)
    const run = await s.workflows.start(p.id, { type: 'solution_generation' })
    expect(run.status).toBe('waiting_human')
    await expect(s.workflows.resume(p.id, run.id)).rejects.toMatchObject({ code: 'WAITING_HUMAN' })
    await expect(s.artifacts.save(p.id, { type: 'solution', name: 'Solution.md', format: 'markdown', content: '# Solution' })).rejects.toMatchObject({ code: 'waiting_human' })
    const [a] = await s.alternatives.addMany(p.id, [alternative])
    await s.decisions.confirm(p.id, { alternativeId: a!.id, decision: 'A', rationale: '人工选择', requirementIds: [r], evidenceIds: [] })
    expect((await s.workflows.resume(p.id, run.id)).status).toBe('running')
  })
  it('records human wait, duration, steps and call counts without invoking a model', async () => {
    const { services: s, project: p, advance } = await setup()
    const run = await s.workflows.start(p.id, { type: 'requirement_analysis' })
    advance(100)
    await s.workflows.step(p.id, run.id, { step: 'LOAD_DOCUMENTS', toolCalls: 1 })
    await s.workflows.wait(p.id, run.id)
    advance(500)
    await expect(s.workflows.resume(p.id, run.id)).rejects.toMatchObject({ code: 'WAITING_HUMAN' })
    await confirmedRequirement(s, p.id)
    await s.workflows.resume(p.id, run.id)
    advance(200)
    const result = await s.workflows.complete(p.id, run.id)
    expect(result).toMatchObject({ status: 'completed', humanWaitMs: 500, durationMs: 800, modelCalls: 0, toolCalls: 1 })
    expect(s.workflows.summary(p.id)).toMatchObject({ requirements: 1, durationMs: 800, humanWaitMs: 500 })
    await expect(s.workflows.resume(p.id, run.id)).rejects.toMatchObject({ code: 'INVALID_TRANSITION' })
    await s.workflows.delete(p.id, run.id)
    expect(s.workflows.list(p.id)).toEqual([])
  })
  it('cancels waiting work and makes terminal transitions immutable', async () => {
    const { services: s, project: p, advance } = await setup()
    const run = await s.workflows.start(p.id, { type: 'tender_review' })
    await expect(s.workflows.delete(p.id, run.id)).rejects.toMatchObject({ code: 'RUN_ACTIVE' })
    await s.workflows.wait(p.id, run.id)
    advance(250)
    expect(await s.workflows.cancel(p.id, run.id)).toMatchObject({ status: 'cancelled', humanWaitMs: 250 })
    await expect(s.workflows.complete(p.id, run.id)).rejects.toMatchObject({ code: 'INVALID_TRANSITION' })
    await expect(s.workflows.step(p.id, run.id, { step: 'SAVE' })).rejects.toMatchObject({ code: 'RUN_NOT_RUNNING' })
  })
  it('preserves meaningful failures', async () => {
    const { services: s, project: p } = await setup()
    const run = await s.workflows.start(p.id, { type: 'tender_review' })
    expect(await s.workflows.fail(p.id, run.id, 'No source text')).toMatchObject({ status: 'failed', error: 'No source text' })
  })
  it('rejects human reviews made stale by a concurrent project edit', async () => {
    const { services: s, repository, project: p } = await setup()
    const [r] = await s.requirements.addMany(p.id, [requirement])
    const withDelayedGate = createServices(repository, { async review(request) {
      await s.projects.update(p.id, { description: 'edited while review was open' })
      return approved.review(request)
    } })
    await expect(withDelayedGate.requirements.confirm(p.id, [r!.id])).rejects.toMatchObject({ code: 'STALE_REVIEW' })
    expect(s.requirements.get(p.id, r!.id).status).toBe('proposed')
  })
  it('keeps UNKNOWN explicit in project context and resets artifact review after edits', async () => {
    const { services: s, project: p } = await setup()
    await s.evidence.add(p.id, { kind: 'UNKNOWN', title: '待确认', statement: '性能指标未冻结', sourceType: 'model' })
    expect(s.projects.getContext(p.id).openUnknowns).toHaveLength(1)
    const a = await s.artifacts.save(p.id, { type: 'other', name: 'Review.md', format: 'markdown', content: '# UNKNOWN' })
    expect((await s.artifacts.approve(p.id, a.id)).reviewStatus).toBe('approved')
    expect((await s.artifacts.update(p.id, a.id, { content: '# Updated UNKNOWN' })).reviewStatus).toBe('draft')
  })
})
