// Bundle the React V4 workbench into one self-contained HTML string (CSP: inline script/style only).
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const result = await build({
  absWorkingDir: root, entryPoints: ['src/workbench-ui/main.tsx'], bundle: true, format: 'iife', minify: true,
  write: false, jsx: 'automatic', platform: 'browser', target: 'es2022', legalComments: 'none', charset: 'utf8', logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
})
const js = result.outputFiles[0]?.text
if (!js) throw new Error('Workbench bundle produced no JavaScript')
const css = (await build({ absWorkingDir: root, entryPoints: ['src/workbench-ui/styles.css'], bundle: true, minify: true, write: false, logLevel: 'warning' }))
  .outputFiles[0].text
// Prevent premature termination of the inline <script>/<style> elements.
const safeJs = js.replace(/<\/(script)/gi, '<\/$1').replace(/<!--/g, '<\!--')
const safeCss = css.replace(/<\/(style)/gi, '<\/$1')
const html = '<!doctype html><html lang="zh-CN"><head><meta charset="utf-8">'
  + '<meta name="viewport" content="width=device-width,initial-scale=1"><title>MarketPilot V4 工作台</title>'
  + `<style>${safeCss}</style></head><body><div id="root"></div><script>${safeJs}</script></body></html>`
const out = fileURLToPath(new URL('../src/harness/v4-page.generated.ts', import.meta.url))
writeFileSync(out, `// Generated by scripts/build-workbench.mjs from src/workbench-ui. Do not edit.\nexport const workbenchPage = ${JSON.stringify(html)}\n`)
console.log(`workbench page: ${(html.length / 1024).toFixed(1)} KiB`)

